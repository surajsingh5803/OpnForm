<?php

namespace App\Http\Controllers\Content;

use App\Http\Controllers\Controller;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\RateLimiter;

class LpProductFeedbackController extends Controller
{
    private function requireFrontendSecret(Request $request): void
    {
        $expected = (string) config('app.front_api_secret', '');
        $provided = (string) $request->header('x-api-secret', '');

        // Publicly deployed Laravel must not accept arbitrary feedback writes.
        // The Nuxt server adds this secret; it is never exposed to the browser.
        abort_unless($expected !== '' && hash_equals($expected, $provided), 403);
    }

    public function index(Request $request): JsonResponse
    {
        $this->requireFrontendSecret($request);

        $items = DB::table('lp_product_feedback')
            ->select(['id', 'title', 'details', 'category', 'status', 'created_at'])
            ->orderByDesc('created_at')
            ->limit(80)
            ->get();

        return response()->json(['items' => $items])
            ->header('Cache-Control', 'no-store');
    }

    public function store(Request $request): JsonResponse
    {
        $this->requireFrontendSecret($request);

        $data = $request->validate([
            'title' => ['required', 'string', 'min:8', 'max:160'],
            'details' => ['required', 'string', 'min:20', 'max:2500'],
            'category' => ['required', 'in:feature,integration,bug,usability'],
            'contact_email' => ['nullable', 'email', 'max:255'],
            'website' => ['nullable', 'string', 'max:255'],
        ]);

        // Honeypot: respond generically to automated submissions, without storage.
        if (!empty($data['website'])) {
            return response()->json(['received' => true], 202);
        }

        // The visitor bucket is a keyed HMAC generated by the trusted Nuxt server.
        // Never use a client-provided IP or header directly as an unbounded key.
        $visitor = (string) $request->header('x-lp-feedback-visitor', '');
        abort_unless(preg_match('/^[a-f0-9]{64}$/', $visitor) === 1, 403);

        $rateKey = 'lp-feedback:hour:' . $visitor;
        if (RateLimiter::tooManyAttempts($rateKey, 5)) {
            return response()->json([
                'message' => 'Please wait before sending another request.',
            ], 429);
        }
        RateLimiter::hit($rateKey, 3600);

        $id = DB::table('lp_product_feedback')->insertGetId([
            'title' => trim(strip_tags($data['title'])),
            'details' => trim(strip_tags($data['details'])),
            'category' => $data['category'],
            'status' => 'review',
            'contact_email' => $data['contact_email'] ?? null,
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        return response()->json(['received' => true, 'id' => $id], 201)
            ->header('Cache-Control', 'no-store');
    }
}
